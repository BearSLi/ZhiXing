#!/bin/sh
# ============================================================
#  容器启动入口（entrypoint）
#  职责：数据库不存在时自动初始化，然后交棒给 CMD 里的启动命令
#  为什么要它：容器是无状态的、随时会被删除重建；
#             而数据库是有状态的、必须落在挂载的卷上。
#             有了这个入口，"删了容器再重建"也能自动恢复可用状态。
# ============================================================
set -e

DB="${DB_PATH:-/app/data/app.db}"
echo "[entrypoint] 数据库路径: $DB"

if [ ! -f "$DB" ]; then
  echo "[entrypoint] 未发现数据库文件，执行初始化（幂等脚本）..."
  python bootstrap_db.py
else
  echo "[entrypoint] 数据库已存在，跳过初始化"
fi

# exec "$@" 让 CMD 里的命令接管 PID 1，保证 docker stop 的信号能正确传递
exec "$@"
